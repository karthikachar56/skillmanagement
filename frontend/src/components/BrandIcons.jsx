export function openWhatsApp(phone, name, customGreeting) {
  if (!phone) {
    alert("This user has not listed a WhatsApp number yet.");
    return;
  }
  // Clean phone: keep digits only
  const cleanPhone = phone.replace(/[^0-9]/g, '');
  const greeting = customGreeting || (name 
    ? `Hello ${name}! I found your profile on SkillBridge and would love to connect about a project collaboration.`
    : "Hello! I saw your profile on SkillBridge and would love to collaborate.");
  const url = `https://wa.me/${cleanPhone}?text=${encodeURIComponent(greeting)}`;
  window.open(url, '_blank', 'noopener,noreferrer');
}
